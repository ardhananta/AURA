import axios from 'axios';

export interface DiseaseStat {
  name: string;
  cases: number;
  trend: 'up' | 'down' | 'stable';
  description: string;
  category: 'Respirasi' | 'Menular' | 'Degeneratif' | 'Lingkungan';
}

export interface JatengRegionHealth {
  id: string;             // e.g. 'reg_33_74'
  code: string;           // e.g. '33.74'
  name: string;           // e.g. 'Kota Semarang'
  shortName: string;      // e.g. 'Semarang'
  isKota: boolean;
  latitude: number;
  longitude: number;
  aqi: number;            // Indeks Kualitas Udara (0-300)
  aqiStatus: 'Baik' | 'Sedang' | 'Tidak Sehat Sensitif' | 'Tidak Sehat' | 'Sangat Tidak Sehat';
  pm25: number;           // µg/m³
  pollutionRank: number;  // Urutan polusi di Jateng (1-35)
  mapColor: string;       // Warna choropleth map
  mapColorClass: 'low' | 'mid' | 'high' | 'critical';
  landmarkName: string;   // Nama landmark ikon (e.g. 'Tugu Muda')
  landmarkDesc: string;   // Deskripsi landmark
  topDiseases: DiseaseStat[];
  totalRespiratoryCases: number;
  healthFacilityCount: {
    rsud: number;
    puskesmas: number;
  };
  population: number;     // Estimasi penduduk
  vulnerableRiskScore: number; // 0 - 100
  healthRecommendation: string;
}

